# Organisation host: the inter-cloud relay (MQTT over mutual TLS, Mosquitto with CRL checks), published on RELAY_PORT of
# this host so that every member host reaches it. Only signed member clouds are configured.
#   relay.sh config         (re)write state/relay/: ACL, Compose file (done by sign-cloud.sh too)
#   relay.sh up | down | status | logs
#   relay.sh crl <Cloud> <ca.crl>   install a member's current CRL (members send it before nextUpdate: OPERATIONS.md)
. "$(dirname -- "$0")/lib-org.sh"
R=$STATE/relay
signed() { for c in $MEMBERS; do [ -f "$STATE/clouds/$c/ca-cross.crt" ] && printf '%s ' "$c"; done; }

config() {
  mkdir -p "$R"
  {
    echo "# generated by org/relay.sh for $SOLC: users are the full relay certificate subjects (RFC 2253); a client reads only"
    echo "# its own cloud's inbox of its own role and writes into other clouds' inboxes only below its own certificate CN"
    for c in $(signed); do
      for s in Gatekeeper GateTunnel; do
        role=$(printf '%s' "$s" | tr 'A-Z' 'a-z')
        printf '\nuser dnQualifier=sy,CN=%s.%s.%s.arrowhead.eu,OU=%s,O=%s,C=SE\n' "$s" "$c" "$ORG" "$c" "$ORG"
        printf 'topic read arrowhead/relay/%s/%s/#\n' "$c" "$role"
        printf 'topic write arrowhead/relay/+/%s/in/%s.%s.%s.arrowhead.eu/#\n' "$role" "$s" "$c" "$ORG"
      done
    done
  } > "$R/acl"
  crl_sources=; cross=; vols=
  for c in $(signed); do
    crl_sources="$crl_sources /crl/$c/ca.crl"; cross="$cross /cross/$c.crt"
    vols="$vols
      - $STATE/clouds/$c:/crl/$c:ro
      - $STATE/clouds/$c/ca-cross.crt:/cross/$c.crt:ro"
  done
  cat > "$R/compose.yaml" <<YAML
# generated by org/relay.sh ($SOLC); do not edit
name: $RELAY_PROJECT
services:
  relay:
    image: arrowhead-solc/relay-mosquitto:2.0.22
    build: {context: $ORG_DIR/relay}
    user: "1883:1883"
    read_only: true
    tmpfs: ["/tmp:size=4m,mode=1777,noexec,nosuid,nodev"]
    cap_drop: [ALL]
    security_opt: ["no-new-privileges:true"]
    mem_limit: 128m
    pids_limit: 64
    entrypoint: ["/mosquitto/config/crl-watch.sh"]
    command: ["/usr/sbin/mosquitto", "-c", "/mosquitto/config/mosquitto.conf"]
    environment:
      CRL_SOURCES: "${crl_sources# }"
      ORG_CA: /certs/org-ca.crt
      ORG_CRL: /crl/org/org-ca.crl
      CROSS_CERTIFICATES: "${cross# }"
    restart: unless-stopped
    ports: ["${RELAY_BIND:-0.0.0.0}:$RELAY_PORT:8883"]
    volumes:
      - $ORG_DIR/relay/mosquitto.conf:/mosquitto/config/mosquitto.conf:ro
      - $R/acl:/mosquitto/config/acl:ro
      - $ORG_DIR/relay/crl-watch.sh:/mosquitto/config/crl-watch.sh:ro
      - $STATE/public:/crl/org:ro
      - $STATE/public/org-ca.crt:/certs/org-ca.crt:ro
      - $R/relay.crt:/certs/relay.crt:ro
      - $R/relay.key:/certs/relay.key:ro$vols
    healthcheck:
      test: ["CMD-SHELL", "nc -z 127.0.0.1 8883"]
      interval: 10s
      timeout: 4s
      retries: 8
YAML
  chmod 644 "$R/acl" "$R/compose.yaml"
  # the relay runs as uid 1883 and must read its key: the file is 0644, but state/relay is 0700, so on this host only the
  # owner reaches it; the container sees it through its bind mount only
  chmod 644 "$R/relay.key"; chmod 700 "$R"; chmod 755 "$STATE"
  echo "relay configured for: $(signed)"
}

case "${1:-}" in
config) config ;;
up)
  need docker
  [ -n "$(signed)" ] || die "no member request signed yet (org/sign-cloud.sh)"
  config
  docker compose -f "$R/compose.yaml" up -d --build --wait
  echo "relay listening on ${RELAY_BIND:-0.0.0.0}:$RELAY_PORT (members use $RELAY_HOST:$RELAY_PORT)" ;;
down) docker compose -f "$R/compose.yaml" down ;;
status) docker compose -f "$R/compose.yaml" ps ;;
logs) docker compose -f "$R/compose.yaml" logs --tail=100 relay ;;
crl)
  c=${2:?cloud}; f=${3:?ca.crl}
  [ -f "$STATE/clouds/$c/ca.crt" ] || die "$c is not signed"
  openssl crl -in "$f" -CAfile "$STATE/clouds/$c/ca.crt" -noout 2>&1 | grep -q "verify OK" || die "CRL not signed by $c's CA"
  cp "$f" "$STATE/clouds/$c/.ca.crl.tmp" && chmod 644 "$STATE/clouds/$c/.ca.crl.tmp" && mv "$STATE/clouds/$c/.ca.crl.tmp" "$STATE/clouds/$c/ca.crl"
  echo "$c: CRL installed ($(openssl crl -in "$STATE/clouds/$c/ca.crl" -noout -nextupdate)); run sign-cloud.sh --bundles to pass it to the peers" ;;
*) die "usage: relay.sh config|up|down|status|logs|crl <Cloud> <ca.crl>" ;;
esac
