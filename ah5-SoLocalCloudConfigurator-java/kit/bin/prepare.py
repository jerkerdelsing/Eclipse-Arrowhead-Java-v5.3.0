"""Credentials of a member cloud installed from an SoLC package (generalised from the v5.3.0 test cloud).

  prepare.py <work-dir>

Run after scripts/init.sh (.env, rotate-secrets.sh generate) and scripts/generate-x509.sh (this cloud's own CA and system
certificates). Idempotent. Adds:
  - every secret of compose.yaml: missing values in .env (random), and secrets/<NAME> (the compose file is JSON, which
    rotate-secrets.sh files does not parse),
  - the certificate of LocalCloudManager (SAN cloud-monitor-api),
  - TLS certificates of every database of compose.yaml,
  - PKCS#12 key/trust stores in the layout of the primary deployments: security/primary-stores/<System>/.
"""
from __future__ import annotations

import json
import pathlib
import secrets
import shutil
import string
import subprocess
import sys

ROOT = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else ".").resolve()
X509, CA_KEY, STORES = ROOT / "security/x509", ROOT / "security/ca/ca.key", ROOT / "security/primary-stores"
def _env(key: str) -> str:
    for line in (ROOT / ".env").read_text().splitlines():
        if line.startswith(key + "="):
            return line.split("=", 1)[1]
    raise SystemExit(f"{key} missing in .env (run configure.py)")


CLOUD_NAME, ORG = _env("ARROWHEAD_CLOUD_NAME"), _env("ARROWHEAD_ORGANIZATION")
CLOUD = f"{CLOUD_NAME}.{ORG}.arrowhead.eu"
COMPOSE = json.loads((ROOT / "compose.yaml").read_text())
# generated by rotate-secrets.sh with their own format; never replaced by a random 32-character value here
NOT_GENERATED = {"CONSOLE_PASSWORD_HASH", "AH_CONSUMER_AUTHORIZATION_CRYPTO_KEY"}

# System -> (certificate file in security/x509, identity password secret, store password secret)
SYSTEMS = {
    "AIGym": ("aigym", "AH_PW_AIG", "AH_STORE_PW_AIG"),
    "Blacklist": ("blacklist", "AH_PW_BL", "AH_STORE_PW_BL"),
    "CertificateAuthority": ("certificate-authority", "AH_PW_CAU", "AH_STORE_PW_CERTAUTH"),
    "Choreographer": ("choreographer", "AH_PW_CHO", "AH_STORE_PW_CHO"),
    "Configuration": ("configuration", "AH_PW_CFG", "AH_STORE_PW_CFG"),
    "DataManager": ("datamanager", "AH_PW_DM", "AH_STORE_PW_DM"),
    "DeviceQoSEvaluator": ("device-qos-evaluator", "AH_PW_DQE", "AH_STORE_PW_DQE"),
    "EventHandler": ("eventhandler", "AH_PW_EH", "AH_STORE_PW_EH"),
    "GateTunnel": ("gatetunnel", "AH_PW_GT", "AH_STORE_PW_GT"),
    "Gatekeeper": ("gatekeeper", "AH_PW_GK", "AH_STORE_PW_GK"),
    "GraphDBManager": ("graphdbmanager", "AH_PW_GDM", "AH_STORE_PW_GDM"),
    "LocalCloudManager": ("local-cloud-manager-spring", "AH_PW_LCM", "AH_STORE_PW_LCM"),
    "Onboarding": ("onboarding", "AH_PW_ONB", "AH_STORE_PW_ONB"),
    "PlantDescriptionEngine": ("plantdescriptionengine", "AH_PW_PDE", "AH_STORE_PW_PDE"),
    "SysMonitor": ("sysmonitor", "AH_PW_SM", "AH_STORE_PW_SM"),
    "TimeManager": ("timemanager", "AH_PW_TMG", "AH_STORE_PW_TMG"),
    "TranslationManager": ("translation-manager", "AH_PW_TM", "AH_STORE_PW_TM"),
}
NEW_CERTS = {"local-cloud-manager-spring": ("LocalCloudManager", "cloud-monitor-api")}
# every MySQL database of the cloud gets a TLS certificate of this cloud's CA (SAN: its service name)
DATABASES = sorted(n for n in COMPOSE["services"] if n.endswith("-db"))


def run(*cmd: str) -> None:
    subprocess.run(cmd, check=True, stdout=subprocess.DEVNULL, stderr=subprocess.PIPE)


def env_values() -> dict[str, str]:
    values = {}
    for line in (ROOT / ".env").read_text().splitlines():
        if "=" in line and not line.lstrip().startswith("#"):
            k, v = line.split("=", 1)
            values[k.strip()] = v
    return values


def ensure_secrets(names: list[str]) -> list[str]:
    env = ROOT / ".env"
    (ROOT / "secrets").mkdir(mode=0o700, exist_ok=True)
    values, added = env_values(), []
    alphabet = string.ascii_letters + string.digits
    for name in names:
        if not values.get(name):
            if name in NOT_GENERATED:
                raise SystemExit(f"{name} is missing in .env: run scripts/init.sh (rotate-secrets.sh generate) first")
            value = "".join(secrets.choice(alphabet) for _ in range(32))
            with env.open("a") as f:
                f.write(f"{name}={value}\n")
            values[name] = value
            added.append(name)
        path = ROOT / "secrets" / name
        if not path.exists() or path.read_text() != values[name]:
            path.write_text(values[name])
            path.chmod(0o600)
    env.chmod(0o600)
    return added


def issue(file_name: str, common_name: str, sans: list[str], usage: str) -> None:
    crt, key = X509 / f"{file_name}.crt", X509 / f"{file_name}.key"
    if crt.exists() and key.exists():
        return
    ext = X509 / f"{file_name}.ext"
    ext.write_text("basicConstraints=critical,CA:FALSE\nkeyUsage=critical,digitalSignature,keyEncipherment\n"
                   f"extendedKeyUsage={usage}\nsubjectAltName={','.join(sans)}\n"
                   "subjectKeyIdentifier=hash\nauthorityKeyIdentifier=keyid,issuer\n")
    csr = X509 / f"{file_name}.csr"
    run("openssl", "genpkey", "-algorithm", "RSA", "-pkeyopt", "rsa_keygen_bits:3072", "-out", str(key))
    run("openssl", "req", "-new", "-sha256", "-key", str(key), "-out", str(csr),
        "-subj", f"/C=SE/O={ORG}/OU=Arrowhead Systems/CN={common_name}/dnQualifier=sy")
    run("openssl", "x509", "-req", "-sha256", "-days", "825", "-in", str(csr), "-CA", str(X509 / "ca.crt"),
        "-CAkey", str(CA_KEY), "-CAcreateserial", "-extfile", str(ext), "-out", str(crt))
    csr.unlink()
    ext.unlink()
    key.chmod(0o600)


def database_certificate(host: str) -> None:
    d = X509 / "db" / host
    d.mkdir(parents=True, exist_ok=True)
    if not (d / "server.crt").exists():
        ext = d / "server.ext"
        ext.write_text("basicConstraints=critical,CA:FALSE\nkeyUsage=critical,digitalSignature,keyEncipherment\n"
                       f"extendedKeyUsage=serverAuth\nsubjectAltName=DNS:{host},DNS:localhost\n")
        run("openssl", "genpkey", "-algorithm", "RSA", "-pkeyopt", "rsa_keygen_bits:3072", "-out", str(d / "server.key"))
        run("openssl", "req", "-new", "-sha256", "-key", str(d / "server.key"), "-out", str(d / "server.csr"),
            "-subj", f"/C=SE/O={ORG}/OU=Arrowhead Databases/CN={host}")
        run("openssl", "x509", "-req", "-sha256", "-days", "825", "-in", str(d / "server.csr"), "-CA",
            str(X509 / "ca.crt"), "-CAkey", str(CA_KEY), "-CAcreateserial", "-extfile", str(ext),
            "-out", str(d / "server.crt"))
        (d / "server.csr").unlink()
        ext.unlink()
    shutil.copy2(X509 / "ca.crt", d / "ca.crt")
    (d / "server.key").chmod(0o600)
    (d / "server.crt").chmod(0o644)
    (d / "ca.crt").chmod(0o644)


def aliases(store: pathlib.Path, password: str) -> set[str]:
    out = subprocess.run(["keytool", "-list", "-keystore", str(store), "-storepass", password], capture_output=True, text=True)
    return {line.split(",")[0].strip().lower() for line in out.stdout.splitlines() if "Entry," in line} if out.returncode == 0 else set()


def stores(system: str, file_name: str, password: str) -> None:
    """PKCS#12 stores of one system. Existing stores with the expected entries are left alone; a changed store is written
    in place (same inode), because running containers bind-mount the files: a replaced file disappears in them
    (FileNotFoundException in GateTunnel, 2026-11-09)."""
    d = STORES / system
    d.mkdir(parents=True, exist_ok=True)
    wanted_trust = {CLOUD.lower()} | ({"test-manufacturer-device-ca"} if system == "Onboarding" else set())
    if aliases(d / f"{system}.p12", password) == {f"{system}.{CLOUD}".lower()} and aliases(d / "truststore.p12", password) == wanted_trust:
        return
    import tempfile
    with tempfile.TemporaryDirectory() as tmp:
        build_stores(system, file_name, password, pathlib.Path(tmp))
        for name in (f"{system}.p12", "truststore.p12"):
            target = d / name
            shutil.copyfile(pathlib.Path(tmp) / name, target)  # in place when the file exists
            target.chmod(0o600)


def build_stores(system: str, file_name: str, password: str, d: pathlib.Path) -> None:
    keystore, truststore = d / f"{system}.p12", d / "truststore.p12"
    run("openssl", "pkcs12", "-export", "-inkey", str(X509 / f"{file_name}.key"), "-in", str(X509 / f"{file_name}.crt"),
        "-certfile", str(X509 / "ca.crt"), "-name", f"{system}.{CLOUD}", "-passout", f"pass:{password}",
        "-out", str(keystore))
    truststore.unlink(missing_ok=True)
    run("keytool", "-importcert", "-noprompt", "-alias", CLOUD, "-file", str(X509 / "ca.crt"), "-storetype", "PKCS12",
        "-keystore", str(truststore), "-storepass", password)
    if system == "Onboarding":
        # Onboarding alone also trusts the test manufacturer CA of the device bootstrap certificates (as the cloud's
        # onboarding-truststore.p12 does); their CRL is added by generate.py
        run("keytool", "-importcert", "-noprompt", "-alias", "test-manufacturer-device-ca", "-file",
            str(X509 / "manufacturer-ca.crt"), "-storetype", "PKCS12", "-keystore", str(truststore), "-storepass", password)
    keystore.chmod(0o600)
    truststore.chmod(0o600)


def main() -> None:
    needed = [n for s in SYSTEMS.values() for n in s[1:]] + list(COMPOSE["secrets"])
    added = ensure_secrets(sorted(set(needed)))
    for file_name, (system, alias) in NEW_CERTS.items():
        issue(file_name, f"{system}.{CLOUD}", [f"DNS:{alias}", "DNS:localhost", "IP:127.0.0.1"], "serverAuth,clientAuth")
    for host in DATABASES:
        database_certificate(host)
    values = env_values()
    for system, (file_name, _, store_secret) in SYSTEMS.items():
        stores(system, file_name, values[store_secret])
    print("added secrets:", ", ".join(added) or "none")
    print("stores:", len(SYSTEMS), "systems in", STORES)


if __name__ == "__main__":
    main()
